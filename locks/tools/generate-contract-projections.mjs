#!/usr/bin/env node

import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  assertPeerParity,
  parseJsonSchema,
  parseTypeSpec,
  reconcileProtoLock,
  validateCatalog,
} from "./projection-ir.mjs";
import {
  renderGrpcManifest,
  renderProto,
  renderReadme,
  renderSeed,
  renderSql,
} from "./projection-render.mjs";

export {
  assertPeerParity,
  parseJsonSchema,
  parseTypeSpec,
  reconcileProtoLock,
  validateCatalog,
} from "./projection-ir.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, "..");
const CHECK = process.argv.includes("--check");
const BANNER = "AUTOGENERATED by locks/tools/generate-contract-projections.mjs — do not edit";

const readText = (relative) => fs.readFileSync(path.join(ROOT, relative), "utf8");
const canonical = (value) => `${JSON.stringify(value, null, 2)}\n`;
const sha256 = (content) => crypto.createHash("sha256").update(content).digest("hex");

export function buildArtifacts({ check = false } = {}) {
  const typeSpecText = readText("contracts/typespec/main.tsp");
  const jsonSchemaText = readText("contracts/json-schema/contract.schema.json");
  const catalogText = readText("catalog.json");
  const configText = readText("projection/config.json");
  const lockText = readText("projection/protobuf.lock.json");
  const config = JSON.parse(configText);
  const catalog = JSON.parse(catalogText);
  const typeSpecIr = parseTypeSpec(typeSpecText);
  const jsonSchemaIr = parseJsonSchema(JSON.parse(jsonSchemaText));

  assertPeerParity(typeSpecIr, jsonSchemaIr);
  validateCatalog(typeSpecIr, catalog, config.rootModel);
  validateCatalog(jsonSchemaIr, catalog, config.rootModel);

  const originalLock = JSON.parse(lockText);
  const reconciledLock = reconcileProtoLock(typeSpecIr, config, originalLock, check);
  const canonicalLock = canonical(reconciledLock);
  if (check) {
    assert.equal(canonicalLock, canonical(originalLock), "protobuf.lock.json is stale or non-canonical");
  }

  const typeSpecSql = renderSql(typeSpecIr, config, BANNER);
  const jsonSchemaSql = renderSql(jsonSchemaIr, config, BANNER);
  assert.equal(typeSpecSql, jsonSchemaSql, "TypeSpec and JSON Schema SQL projections differ");
  const proto = renderProto(typeSpecIr, config, reconciledLock, BANNER);
  const seed = renderSeed(catalog, config, BANNER);
  const grpcManifest = renderGrpcManifest(config, sha256(proto), canonical);

  const outputDigests = {
    "sql/from-typespec.sql": sha256(typeSpecSql),
    "sql/from-json-schema.sql": sha256(jsonSchemaSql),
    "sql/catalog-seed.sql": sha256(seed),
    "protobuf/agent_pontifex/locks/v1/locks.proto": sha256(proto),
    "grpc/manifest.json": sha256(grpcManifest),
  };
  const manifest = canonical({
    formatVersion: 1,
    authorityPolicy: "peer-human-authored",
    sources: {
      typeSpecSha256: sha256(typeSpecText),
      jsonSchemaSha256: sha256(jsonSchemaText),
      catalogSha256: sha256(catalogText),
      projectionConfigSha256: sha256(configText),
      protobufLockSha256: sha256(canonicalLock),
    },
    declarations: Object.keys(typeSpecIr).sort(),
    outputs: outputDigests,
    grpcService: `${config.protoPackage}.${config.service.name}/${config.service.method}`,
    sqlLanesEqual: true,
  });

  return {
    lock: canonicalLock,
    files: {
      "generated/README.md": renderReadme(BANNER),
      "generated/sql/from-typespec.sql": typeSpecSql,
      "generated/sql/from-json-schema.sql": jsonSchemaSql,
      "generated/sql/catalog-seed.sql": seed,
      "generated/protobuf/agent_pontifex/locks/v1/locks.proto": proto,
      "generated/grpc/manifest.json": grpcManifest,
      "generated/manifest.json": manifest,
    },
    report: {
      ok: true,
      declarations: Object.keys(typeSpecIr).length,
      catalogEntries: catalog.entries.length,
      grpcService: `${config.protoPackage}.${config.service.name}/${config.service.method}`,
      sqlLanesEqual: true,
    },
  };
}

function writeOrCheck(relative, content, check) {
  const absolute = path.join(ROOT, relative);
  if (check) {
    assert.ok(fs.existsSync(absolute), `${relative}: generated file is missing`);
    assert.equal(fs.readFileSync(absolute, "utf8"), content, `${relative}: generated drift`);
    return;
  }
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, content);
}

export function run({ check = CHECK } = {}) {
  const artifacts = buildArtifacts({ check });
  writeOrCheck("projection/protobuf.lock.json", artifacts.lock, check);
  for (const [relative, content] of Object.entries(artifacts.files)) {
    writeOrCheck(relative, content, check);
  }
  console.log(JSON.stringify(artifacts.report, null, 2));
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  run();
}
